#!/usr/bin/env python3
"""Check a strategy workspace instance and write reports/impact-YYYYMMDD.md.

Reads the same wikilinks and properties Obsidian uses (graph.py) and runs:
- check_evidence.py: sources, originals as served, quotes and quoted DATA fragments against the
  original, DATA values, quotes cut before a condition;
- check_traceability.py: links and required fields along the chain, framework fields, gaps, alert
  propagation (claim -> conclusion -> decision -> direction/OKR), budgets, reviews, unused claims.
Never changes a status.

Usage: python3 scripts/check.py <instance-dir> [--today YYYY-MM-DD]
Exit 1 on validation errors or a hard budget exceeded. Requires PyYAML: run it from the
instance venv (see requirements.txt). Quotes in PDFs need pdftotext (poppler-utils);
without it they are listed as not checked.
"""
import argparse
import datetime as dt
import sys
from pathlib import Path

import check_evidence
import check_traceability
from graph import Graph, yaml


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("vault", type=Path)
    ap.add_argument("--today", type=dt.date.fromisoformat, default=dt.date.today())
    args = ap.parse_args()
    vault, today = args.vault, args.today

    cfg_path = vault / "strategy.config.yaml"
    cfg = (yaml.safe_load(cfg_path.read_text(encoding="utf-8")) or {}) if cfg_path.exists() else {}
    g = Graph(vault)
    errors = g.errors
    if not cfg_path.exists():
        errors.append("`strategy.config.yaml` not found: using default budgets")
    ev = check_evidence.check(g, errors)
    tr = check_traceability.check(g, cfg, today, errors)

    out = [f"# Impact report {today}", "",
           "Generated by `scripts/check.py`. It changes no status: a person decides.", "",
           f"Relations marked: {ev.relations['confirms']} confirms, {ev.relations['contradicts']} contradicts.", "",
           "## Validation", ""] + ([f"- {e}" for e in errors] or ["No errors."])
    sections = [
        ("Quotes verified manually", ev.manual),
        ("Quotes not checked automatically", ev.unchecked),
        ("Quotes cut before a condition", ev.cut),
        ("DATA values not found", ev.values),
        ("Affected", ["| Item | Type | Reason | Path |", "| --- | --- | --- | --- |"]
         + check_traceability.affected_rows(g, tr.affected)),
        ("Budgets", ["| Budget | Current | Soft | Hard | State |", "| --- | --- | --- | --- | --- |"] + tr.budgets),
        ("Reviews due", tr.due),
        ("Archive candidates", ["Expired and not relied on by any live decision.", ""] + (tr.archive or ["None."])),
        ("Unused claims", tr.unused),
    ]
    for title, lines in sections:
        out += ["", f"## {title}", ""] + (lines or ["None."])
    report = vault / "reports" / f"impact-{today:%Y%m%d}.md"
    report.parent.mkdir(exist_ok=True)
    report.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{report}: {len(errors)} errors, {len(tr.affected)} affected, "
          f"hard budget exceeded: {'yes' if tr.hard else 'no'}")
    return 1 if errors or tr.hard else 0


if __name__ == "__main__":
    sys.exit(main())
